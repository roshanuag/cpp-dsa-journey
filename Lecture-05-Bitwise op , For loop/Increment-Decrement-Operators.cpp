/*In this code we will be doing pre increment, post increment, 
pre decrememt and post decrement.
*/


#include <iostream>
using namespace std;

int main(){

    int i = 7;

    cout << (++i) <<endl; //Pre
    cout << (i++) <<endl ; //Post
    cout << (i--) <<endl; //Post
    cout << (--i) <<endl; //Pre

}